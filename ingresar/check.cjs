const assert=require('node:assert/strict');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
(async()=>{
  const browser=await chromium.launch({headless:true,channel:'chrome'});
  const context=await browser.newContext({viewport:{width:390,height:844}});
  const page=await context.newPage(),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  const base=process.env.LOGIN_URL||'http://127.0.0.1:8767/dist/ingresar/';
  try{
    await context.route('**/auth/v1/settings',r=>r.fulfill({json:{external:{google:false}}}));
    await page.goto(base);
    await page.getByText('Estamos preparando el acceso con Google.',{exact:false}).waitFor();
    assert.equal(await page.locator('#google').isDisabled(),true,'unconfigured provider must not start OAuth');
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'mobile overflow');
    await context.unroute('**/auth/v1/settings');
    await context.route('**/auth/v1/settings',r=>r.fulfill({json:{external:{google:true}}}));
    await page.goto(base+'?error=access_denied');
    await page.getByText('No se completó el acceso. Podés reintentar con Google.').waitFor();
    assert.equal(await page.locator('#google').isEnabled(),true,'cancelled login must allow retry');
    assert.equal(new URL(page.url()).search,'','OAuth error cleared from URL');
    let redirect;
    await context.route('**/auth/v1/authorize?**',r=>{redirect=new URL(r.request().url());return r.fulfill({contentType:'text/html',body:'OAuth intercepted in isolated test.'})});
    await page.reload();
    await page.getByText('Usá tu cuenta de Google para entrar.').waitFor();
    await page.locator('#google').click();
    await page.waitForURL('**/auth/v1/authorize?**');
    assert.equal(redirect.searchParams.get('provider'),'google');
    assert.equal(redirect.searchParams.get('code_challenge_method'),'s256');
    assert.equal(redirect.searchParams.get('redirect_to'),new URL('/ingresar/',base).href);
    await context.unroute('**/auth/v1/authorize?**');
    await page.goto(base);
    const config=await (await page.request.get(new URL('../assets/config.json',base).href)).json();
    const ref=new URL(config.supabaseUrl).hostname.split('.')[0];
    const user={id:'00000000-0000-0000-0000-000000000002',email:'test@example.invalid',aud:'authenticated',app_metadata:{},user_metadata:{}};
    const exp=Math.floor(Date.now()/1000)+3600;
    const token=`e30.${Buffer.from(JSON.stringify({sub:user.id,role:'authenticated',exp})).toString('base64url')}.test`;
    await page.evaluate(({ref,token,user,exp})=>localStorage.setItem(`sb-${ref}-auth-token`,JSON.stringify({access_token:token,refresh_token:'test-only',expires_at:exp,expires_in:3600,token_type:'bearer',user})),{ref,token,user,exp});
    await context.route('**/rest/v1/rpc/my_access',r=>r.fulfill({json:{is_admin:false,has_access:false}}));
    await page.reload();
    await page.getByText('La membresía todavía no está activa',{exact:false}).waitFor();
    assert.equal(await page.locator('#signed-out').isVisible(),false);
    let billing={offer:{amount_cents:5000,currency:'PEN'},membership:{status:'pending'},subscription:null,is_admin:true,mode:'test',sales_open:false,terms_version:'2026-11-03-preventa'};
    let rejectCancel=false,cancelCalls=0;
    await context.route('**/api/billing',async r=>{
      const body=r.request().method()==='POST'?r.request().postDataJSON():{};
      if(body.action==='cancel'){
        cancelCalls++;
        if(rejectCancel)return r.fulfill({status:502,json:{error:'cancellation_unconfirmed'}});
        billing={...billing,subscription:{...billing.subscription,state:'cancelled'}};
      }
      return r.fulfill({json:billing});
    });
    await page.reload();
    await page.getByText('Sin suscripción',{exact:true}).waitFor();
    assert.equal(await page.locator('#subscribe').isDisabled(),true,'terms must be accepted');
    await page.locator('#payment-terms').check();
    assert.equal(await page.locator('#subscribe').isEnabled(),true);
    billing={...billing,subscription:{id:'sub',state:'authorized',cancellation_requested:false}};
    await page.reload();
    await page.getByText('Autorizada · verificando cobro',{exact:true}).waitFor();
    assert.equal(await page.locator('#billing-status').textContent().then(t=>t.includes('aprobado')),false,'mandate is not payment proof');
    billing={...billing,subscription:{...billing.subscription,latest_invoice:{status:'approved'}}};
    await page.locator('#refresh-payment').click();
    await page.getByText('Pago de prueba aprobado',{exact:true}).waitFor();
    await page.locator('#cancel-payment').click();
    assert.equal(cancelCalls,0,'opening cancel confirmation must not cancel');
    rejectCancel=true;
    await page.locator('#confirm-cancel').click();
    await page.getByText('Mercado Pago todavía no confirmó la cancelación.',{exact:false}).waitFor();
    assert.equal(await page.locator('#billing-status').textContent(),'Pago de prueba aprobado','failed cancellation must not show cancelled');
    rejectCancel=false;
    await page.locator('#confirm-cancel').click();
    await page.getByText('Cancelación confirmada. No habrá nuevas renovaciones.').waitFor();
    assert.equal(await page.locator('#cancel-payment').isVisible(),false);
    await page.setViewportSize({width:320,height:740});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'billing 320px overflow');
    await page.screenshot({path:__dirname+'/preview-billing.png',fullPage:true});
    await page.locator('#logout').click();
    await page.getByText('Usá tu cuenta de Google para entrar.').waitFor();
    await page.setViewportSize({width:320,height:740});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'320px overflow');
    await page.screenshot({path:__dirname+'/preview-login.png',fullPage:true});
    assert.deepEqual(errors,[]);
    assert.equal(await page.locator('#billing').isVisible(),false,'sign-out hides billing');
    console.log('PASS: provider unavailable, mobile layout, PKCE, unpaid session, billing consent, verified payment states, cancellation errors and sign-out. Provider transactions require separate integration tests.');
  }finally{await context.close();await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1});
